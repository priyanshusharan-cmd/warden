"""Record real engine output into frontend/js/demo-data.js so the console works with the server off.

    python3 scripts/build_demo_data.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))

from warden import benchmark as bench, config  # noqa: E402
from warden.api import handlers as server  # noqa: E402
from warden.core.audit import AuditLog  # noqa: E402
from warden.workspace import scenarios  # noqa: E402

server.STATE = server.State()
audit = AuditLog()
runs = {}
for sc in scenarios.all_scenarios():
    res = server.api_run({"scenario_id": sc.id, "agent": "scripted"})
    entry = {k: res[k] for k in ("scenario", "planted", "agent_acted", "open", "guarded")}
    if res["guarded"]["status"] == "waiting":
        for key, ok in (("approve", True), ("block", False)):
            r = bench.start(sc, True)
            r.resume(r.waiting_step.approval_id, ok)
            entry[key] = bench.finish(r).state()
    runs[sc.id] = entry
    bench.finish(bench.start(sc, True, audit=audit))

drifted = server.api_tools_drift({"tool": "get_weather"})
server.api_tools_reset({})
data = {
    "meta": server.api_meta({}),
    "scenarios": server.api_scenarios({}),
    "runs": runs,
    "bench": bench.run_all(),
    "tools": server.api_tools({}),
    "tools_drifted": drifted,
    "audit": {"entries": audit.entries[:60]},
}
out = config.FRONTEND_DIR / "js" / "demo-data.js"
out.write_text("// Generated by scripts/build_demo_data.py. Recorded engine output for offline demos.\n"
               "window.WARDEN_DEMO = " + json.dumps(data, ensure_ascii=False) + ";\n")
print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
